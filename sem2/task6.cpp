// Принятые допущения:
// 1) площадь крыла S и коэффициент C_L дополнительно вводятся
//    с клавиатуры (в условии они не заданы);
// 2) S и C_L считаются одинаковыми на всех шагах траектории;
// 3) подъемная сила рассчитывается по формуле задачи 1:
//    L = 0.5 * rho * V^2 * S * C_L.

#include <iostream>
#include <iomanip>

int main() {
    const int N = 6;
    double V[N] = { 60, 80, 100, 120, 140, 160 };
    double rho[N] = { 1.225, 1.167, 1.112, 1.007, 0.909, 0.819 };

    double S, CL;

    std::cout << "Расчет подъемной силы на траектории" << std::endl;
    std::cout << "Введите площадь крыла S (м2): ";
    std::cin >> S;
    std::cout << "Введите коэффициент подъемной силы CL: ";
    std::cin >> CL;

    if (S <= 0.0 || CL <= 0.0) {
        std::cout << "Ошибка: параметры должны быть положительными." << std::endl;
        return 1;
    }

    std::cout << std::fixed << std::setprecision(2);
    std::cout << std::endl;
    std::cout << "| Шаг | Скорость, м/с | Плотность, кг/м3 | Подъемная сила, Н |" << std::endl;
    std::cout << "|-----|---------------|------------------|-------------------|" << std::endl;

    for (int i = 0; i < N; ++i) {
        double L = 0.5 * rho[i] * V[i] * V[i] * S * CL;
        std::cout << "| " << std::setw(3) << i
                  << " | " << std::setw(13) << V[i]
                  << " | " << std::setw(16) << rho[i]
                  << " | " << std::setw(17) << L << " |" << std::endl;
    }

    return 0;
}