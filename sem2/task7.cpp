// Принятые допущения:
// 1) масса m дополнительно вводится с клавиатуры (в условии ее нет);
// 2) режим определяется ускорением по тяге a = (T - D) / m;
// 3) границы режимов: a > 0.5 — «набор высоты»,
//    0 <= a <= 0.5 — «горизонтальный полет», a < 0 — «снижение».

#include <iostream>

int main() {
    double T, L, D, m;

    std::cout << "Автоматический выбор режима полета" << std::endl;
    std::cout << "Введите тягу двигателя T (Н): ";
    std::cin >> T;
    std::cout << "Введите подъемную силу L (Н): ";
    std::cin >> L;
    std::cout << "Введите силу сопротивления D (Н): ";
    std::cin >> D;
    std::cout << "Введите массу ЛА m (кг): ";
    std::cin >> m;

    if (m <= 0.0) {
        std::cout << "Ошибка: масса должна быть положительной." << std::endl;
        return 1;
    }

    const double g = 9.81;
    double a = (T - D) / m;
    double ay = (L - m * g) / m;

    std::cout << "Ускорение по направлению движения: a = " << a << " м/с2" << std::endl;
    std::cout << "Вертикальное ускорение:            ay = " << ay << " м/с2" << std::endl;

    if (a > 0.5) {
        std::cout << "Режим полета: «набор высоты»" << std::endl;
    } else if (a >= 0.0) {
        std::cout << "Режим полета: «горизонтальный полет»" << std::endl;
    } else {
        std::cout << "Режим полета: «снижение»" << std::endl;
    }

    return 0;
}